CREATE TABLE customer_companies (
    company_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(150) NOT NULL UNIQUE
);

ALTER TABLE team_users
    ADD COLUMN company_id integer REFERENCES customer_companies (company_id),
    DROP CONSTRAINT team_users_role_check,
    ADD CONSTRAINT team_users_role_check CHECK (
        (role IN ('admin', 'editor', 'viewer') AND company_id IS NULL)
        OR (role = 'customer' AND company_id IS NOT NULL)
    );

CREATE TABLE customer_invitations (
    token_hash varchar(64) PRIMARY KEY,
    company_id integer NOT NULL REFERENCES customer_companies (company_id),
    username varchar(64) NOT NULL,
    expires_at timestamptz NOT NULL,
    consumed_at timestamptz
);

CREATE TABLE customer_jobs (
    job_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id integer NOT NULL REFERENCES customer_companies (company_id),
    reference varchar(64) NOT NULL,
    title varchar(150) NOT NULL,
    status varchar(20) NOT NULL CHECK (status IN ('received', 'in_progress', 'ready', 'delivered', 'cancelled')),
    expected_delivery date,
    UNIQUE (company_id, reference)
);
