CREATE TABLE team_users (
    user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(64) NOT NULL UNIQUE,
    password_hash varchar(160) NOT NULL,
    role varchar(10) NOT NULL CHECK (role IN ('admin', 'editor', 'viewer')),
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE team_sessions (
    token_hash varchar(64) PRIMARY KEY,
    user_id integer NOT NULL REFERENCES team_users (user_id) ON DELETE CASCADE,
    expires_at timestamptz NOT NULL
);
CREATE INDEX ix_team_sessions_user_id ON team_sessions (user_id);
CREATE INDEX ix_team_sessions_expires_at ON team_sessions (expires_at);

CREATE TABLE login_attempts (
    client_ip varchar(64) PRIMARY KEY,
    attempts integer NOT NULL,
    expires_at timestamptz NOT NULL
);
CREATE INDEX ix_login_attempts_expires_at ON login_attempts (expires_at);
