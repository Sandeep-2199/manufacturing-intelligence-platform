CREATE TABLE knowledge_documents (
    document_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(150) NOT NULL UNIQUE,
    added_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE knowledge_passages (
    document_id integer NOT NULL REFERENCES knowledge_documents ON DELETE CASCADE,
    passage_number integer NOT NULL,
    content text NOT NULL,
    search_vector tsvector GENERATED ALWAYS AS (to_tsvector('english', content)) STORED,
    PRIMARY KEY (document_id, passage_number)
);

CREATE INDEX ix_knowledge_passages_search ON knowledge_passages USING GIN (search_vector);
