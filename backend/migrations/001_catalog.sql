CREATE TABLE IF NOT EXISTS products (
    product_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_number varchar(50) NOT NULL UNIQUE,
    product_name varchar(150) NOT NULL,
    description text,
    material varchar(100),
    unit varchar(30),
    is_active boolean,
    created_at timestamptz DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_products_product_id ON products (product_id);

CREATE TABLE IF NOT EXISTS vendors (
    vendor_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_code varchar(50) NOT NULL UNIQUE,
    vendor_name varchar(150) NOT NULL
);

CREATE TABLE IF NOT EXISTS vendor_products (
    vendor_id integer REFERENCES vendors (vendor_id),
    product_id integer REFERENCES products (product_id),
    unit_price numeric(12, 2) CONSTRAINT ck_vendor_products_price CHECK (unit_price >= 0),
    lead_time_days integer CONSTRAINT ck_vendor_products_lead_time CHECK (lead_time_days >= 0),
    PRIMARY KEY (vendor_id, product_id)
);
CREATE INDEX IF NOT EXISTS ix_vendor_products_product_id ON vendor_products (product_id);
