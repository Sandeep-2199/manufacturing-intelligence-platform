CREATE TABLE machines (
    machine_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(50) NOT NULL UNIQUE,
    name varchar(150) NOT NULL,
    status varchar(20) NOT NULL CHECK (status IN ('running', 'idle', 'maintenance', 'offline'))
);
CREATE TABLE stock_items (
    item_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku varchar(50) NOT NULL UNIQUE,
    name varchar(150) NOT NULL,
    unit varchar(30) NOT NULL,
    quantity integer NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    reorder_point integer NOT NULL CHECK (reorder_point >= 0)
);
CREATE TABLE stock_movements (
    movement_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id integer NOT NULL REFERENCES stock_items,
    delta integer NOT NULL CHECK (delta <> 0),
    reason varchar(150) NOT NULL,
    recorded_by integer NOT NULL REFERENCES team_users,
    recorded_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_stock_movements_item ON stock_movements (item_id, movement_id DESC);

CREATE TABLE production_runs (
    run_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id integer NOT NULL REFERENCES machines,
    product_id integer NOT NULL REFERENCES products,
    job_id integer REFERENCES customer_jobs,
    production_date date NOT NULL,
    planned_minutes integer NOT NULL CHECK (planned_minutes BETWEEN 1 AND 1440),
    run_minutes integer NOT NULL CHECK (run_minutes BETWEEN 0 AND planned_minutes),
    ideal_cycle_seconds integer NOT NULL CHECK (ideal_cycle_seconds > 0),
    units_produced integer NOT NULL CHECK (units_produced >= 0),
    units_rejected integer NOT NULL CHECK (units_rejected BETWEEN 0 AND units_produced),
    CHECK (units_produced::bigint * ideal_cycle_seconds <= run_minutes * 60)
);
CREATE INDEX ix_production_runs_date ON production_runs (production_date DESC);

CREATE TABLE quality_checks (
    check_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id integer NOT NULL REFERENCES production_runs,
    inspected integer NOT NULL CHECK (inspected > 0),
    rejected integer NOT NULL CHECK (rejected BETWEEN 0 AND inspected),
    notes varchar(500),
    recorded_by integer NOT NULL REFERENCES team_users,
    recorded_at timestamptz NOT NULL DEFAULT now()
);
